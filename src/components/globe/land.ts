interface Ring {
  points: number[];
  minLon: number;
  maxLon: number;
  minLat: number;
  maxLat: number;
}

function toRing(points: number[]): Ring {
  const ring: Ring = { points, minLon: 180, maxLon: -180, minLat: 90, maxLat: -90 };
  for (let i = 0; i < points.length; i += 2) {
    ring.minLon = Math.min(ring.minLon, points[i]);
    ring.maxLon = Math.max(ring.maxLon, points[i]);
    ring.minLat = Math.min(ring.minLat, points[i + 1]);
    ring.maxLat = Math.max(ring.maxLat, points[i + 1]);
  }
  return ring;
}

const LAND_RINGS = LAND.map(toRing);
const WATER_RINGS = WATER.map(toRing);

/** Even-odd ray cast in the lon/lat plane; no ring crosses the antimeridian. */
function inside(ring: Ring, lon: number, lat: number): boolean {
  if (lon < ring.minLon || lon > ring.maxLon || lat < ring.minLat || lat > ring.maxLat) return false;
  const p = ring.points;
  let hit = false;
  for (let i = 0, j = p.length - 2; i < p.length; j = i, i += 2) {
    const yi = p[i + 1];
    const yj = p[j + 1];
    if (yi > lat !== yj > lat && lon < ((p[j] - p[i]) * (lat - yi)) / (yj - yi) + p[i]) hit = !hit;
  }
  return hit;
}

export function isLand(lat: number, lon: number): boolean {
  // Antarctica, as a cap: the camera never turns that far south.
  if (lat < -70) return true;
  if (!LAND_RINGS.some((ring) => inside(ring, lon, lat))) return false;
  return !WATER_RINGS.some((ring) => inside(ring, lon, lat));
}
